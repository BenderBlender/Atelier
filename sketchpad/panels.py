"""Contextual inspector: one task per page, infrequent settings in foldouts."""
from PySide6.QtCore import Qt, QSize
from PySide6.QtGui import QColor, QIcon, QPixmap
from PySide6.QtWidgets import (QFrame, QWidget, QVBoxLayout, QHBoxLayout, QScrollArea,
    QTabWidget, QComboBox, QCheckBox, QSpinBox, QSlider, QLineEdit, QProgressBar, QListWidget)
from .brush import PRESETS
from .model import PAPER_STYLES
from .widgets import Foldout, button, label


class InspectorPanels:
    def inspector_page(self, tab, title):
        scroll = QScrollArea()
        scroll.setWidgetResizable(True)
        scroll.setHorizontalScrollBarPolicy(Qt.ScrollBarPolicy.ScrollBarAlwaysOff)
        panel = QWidget()
        panel.setObjectName('inspectorPage')
        self.side = QVBoxLayout(panel)
        self.side.setContentsMargins(14, 20, 14, 16)
        self.side.setSpacing(14)
        heading = label(title, 'panelTitle')
        self.side.addWidget(heading)
        scroll.setWidget(panel)
        self.sidebar_tabs.addTab(scroll, tab)
        return heading

    def build_sidebar(self, preview_class):
        sidebar = QFrame()
        sidebar.setObjectName('sidebar')
        sidebar.setFixedWidth(304)
        outer = QVBoxLayout(sidebar)
        outer.setContentsMargins(6, 12, 6, 0)
        self.sidebar_tabs = QTabWidget()
        self.sidebar_tabs.setDocumentMode(True)
        self.sidebar_tabs.setFocusPolicy(Qt.FocusPolicy.NoFocus)
        self.sidebar_tabs.tabBar().setExpanding(True)
        self.sidebar_tabs.tabBar().setDrawBase(False)
        self.sidebar_tabs.tabBar().setFocusPolicy(Qt.FocusPolicy.NoFocus)
        outer.addWidget(self.sidebar_tabs)
        self.build_brush_page(preview_class)
        self.build_guides_page()
        self.build_sheets_page()
        self.inspector_page('Объём', 'Объёмная сетка')
        from .perspective_panel import PerspectivePanel
        self.perspective_panel = PerspectivePanel(self)
        self.side.addWidget(self.perspective_panel)
        self.sidebar_tabs.currentChanged.connect(lambda _: self.board.setFocus())
        return sidebar

    def build_brush_page(self, preview_class):
        self.brush_title = self.inspector_page('Кисть', 'Карандаш')
        self.side.removeWidget(self.brush_title)
        heading = QHBoxLayout()
        heading.addWidget(self.brush_title, 1)
        self.brush_reset = button('↺', self.reset_brush, 'Сбросить выбранную кисть к исходным настройкам')
        self.brush_reset.setFixedWidth(34)
        self.brush_reset.setAccessibleName('Сбросить настройки кисти')
        heading.addWidget(self.brush_reset)
        self.side.insertLayout(0, heading)
        self.presets = QComboBox()
        self.presets.addItems(PRESETS)
        self.presets.setAccessibleName('Пресет карандаша')
        self.presets.currentTextChanged.connect(self.preset_changed)
        self.side.addWidget(self.presets)
        self.eraser_form = QWidget()
        form = QVBoxLayout(self.eraser_form)
        form.setContentsMargins(0, 0, 0, 0)
        form.setSpacing(7)
        form.addWidget(label('Форма клячки', 'muted'))
        self.eraser_shape = QComboBox()
        self.eraser_shape.addItem('Круглая', 'round')
        self.eraser_shape.addItem('Как карандаш', 'pencil')
        self.eraser_shape.setToolTip('Та же толщина, острота, наклон и зерно карандаша — со снятием пигмента.')
        self.eraser_shape.currentIndexChanged.connect(self.change_eraser_shape)
        form.addWidget(self.eraser_shape)
        self.side.addWidget(self.eraser_form)
        self.preview = preview_class(self.board)
        self.side.addWidget(self.preview)

        self.palette = QWidget()
        colors = QHBoxLayout(self.palette)
        colors.setContentsMargins(0, 2, 0, 2)
        colors.setSpacing(12)
        self.color_buttons = {}
        for color, title in [((45,43,40), 'Графит'), ((104,66,48), 'Сепия'), ((62,88,112), 'Синий'), ((147,65,51), 'Сангина'), ((255,255,255), 'Белый · блики и свет')]:
            control = button('', lambda checked=False, c=color: self.set_color(c), title, True)
            control.setAccessibleName(title)
            control.setFixedSize(36, 36)
            control.setStyleSheet(f'QPushButton {{ background: rgb{color}; border: 2px solid #4b514e; border-radius: 18px; }} QPushButton:hover {{ border-color: #a2aaa4; }} QPushButton:checked {{ border: 3px solid #ddc294; }}')
            control.setChecked(color == self.board.brush.color)
            self.color_buttons[color] = control
            colors.addWidget(control)
        colors.addStretch()
        self.side.addWidget(self.palette)
        self.slider('Толщина', 'size', 5, 160, 32, 10, ' px')
        self.controls['size'][0].setToolTip('[ — уменьшить, ] — увеличить. В русской раскладке: Х и Ъ. Работает и с Alt для направляющих.')
        self.slider('Размер круглой клячки', 'eraser_size', 3, 100, 22, 1, ' px')
        self.controls['eraser_size'][0].setToolTip('[ — уменьшить клячку, ] — увеличить. В русской раскладке: Х и Ъ.')
        self.slider('Острота кончика', 'tip_sharpness', 0, 100, 50, 100, '%')
        self.controls['tip_sharpness'][0].setToolTip('0% — притуплённый, 50% — исходная заточка, 100% — тонкое остриё.')
        self.slider('Боковая грань грифеля', 'tilt_gain', 0, 120, 65, 10, '×')
        self.controls['tilt_gain'][0].setToolTip('Насколько раскрывается боковая грань при наклоне. 0 — рисование только остриём.')
        self.slider('Длина заточки', 'sharpening_length', 25, 1000, 100, 100, '%')
        self.controls['sharpening_length'][0].setToolTip('Длина открытого грифеля вдоль наклона: 25% — короткая, 100% — прежняя, 1000% — очень длинная заточка. Боковой штрих становится шире при движении поперёк наклона; вертикальное остриё не меняется.')
        self.slider('Плотность штриха', 'opacity', 5, 100, 74, 100, '%')
        self.slider('Сила клячки', 'eraser_strength', 5, 100, 65, 100, '%')
        self.controls['eraser_strength'][0].setToolTip('Лёгкий нажим мягко снимает тон; сильный нажим и повторные проходы снимают больше.')
        self.eraser_hint = label('Форма и длина заточки — от текущего карандаша.', 'muted')
        self.eraser_hint.setWordWrap(True)
        self.side.addWidget(self.eraser_hint)

        main = self.side
        self.brush_detail = Foldout('Фактура и поведение')
        main.addWidget(self.brush_detail)
        self.side = self.brush_detail.content
        self.slider('Зерно бумаги', 'grain', 0, 100, 67, 100, '%')
        self.slider('Кривая нажима', 'pressure_gamma', 30, 200, 85, 100, '')
        self.slider('Стабилизация', 'smoothing', 0, 85, 12, 100, '%')
        self.pen_detail = Foldout('Перо и диагностика')
        main.addWidget(self.pen_detail)
        self.side = self.pen_detail.content
        self.pen_backend = QComboBox()
        self.pen_backend.addItems(['Wacom · прямое чтение', 'Стандартный ввод Qt'])
        self.pen_backend.setToolTip('Прямое чтение получает нажим, наклон и координаты независимо от мыши.')
        self.pen_backend.currentIndexChanged.connect(self.change_pen_backend)
        self.side.addWidget(self.pen_backend)
        self.pen_live = label('Перо: ожидаю касания\nНажим —    Наклон —', 'muted')
        self.pen_live.setWordWrap(True)
        self.side.addWidget(self.pen_live)
        self.device_label = label('Коснитесь листа пером Wacom', 'muted')
        self.device_label.setWordWrap(True)
        self.side.addWidget(self.device_label)
        self.pressure = QProgressBar()
        self.pressure.setRange(0, 1000)
        self.pressure.setTextVisible(False)
        self.pressure.setFixedHeight(5)
        self.side.addWidget(self.pressure)
        self.telemetry_label = label('Нажим —     Наклон X — / Y —', 'muted')
        self.telemetry_label.setWordWrap(True)
        self.side.addWidget(self.telemetry_label)
        self.input_label = label('Мышь: проверка…', 'muted')
        self.input_label.setWordWrap(True)
        self.side.addWidget(self.input_label)
        main.addStretch()

    def build_guides_page(self):
        self.inspector_page('Пины', 'Направляющие')
        self.dual_button = button('Ручное управление', self.toggle_dual, 'M — переключить управление мышью и пером', True)
        self.side.addWidget(self.dual_button)
        self.dual_hint = label('Расположите резинки и рисуйте вдоль них.', 'muted')
        self.dual_hint.setWordWrap(True)
        self.side.addWidget(self.dual_hint)
        self.side.addWidget(label('Пин для независимого управления мышью', 'muted'))
        self.pin_combo = QComboBox()
        self.pin_combo.setToolTip('Цель мыши остаётся выбранной во время рисования пером.')
        self.pin_combo.currentIndexChanged.connect(self.choose_pin)
        self.side.addWidget(self.pin_combo)
        self.separator()
        self.side.addWidget(label('РЕЗИНКИ', 'eyebrow'))
        self.band_combo = QComboBox()
        self.band_combo.currentIndexChanged.connect(self.choose_band)
        self.side.addWidget(self.band_combo)
        actions = QHBoxLayout()
        actions.addWidget(button('+ Пин · P', lambda: self.board.set_tool('pin')))
        actions.addWidget(button('Соединить · G', lambda: self.board.set_tool('band')))
        self.side.addLayout(actions)
        self.delete_band_button = button('Удалить резинку', lambda: self.board.delete_band(), 'Удалить выбранное соединение, сохранив оба пина. Ctrl+Z — вернуть.')
        self.side.addWidget(self.delete_band_button)
        self.snap_check = QCheckBox('Привязать штрих к резинке')
        self.snap_check.toggled.connect(lambda value: setattr(self.board, 'snap', value))
        self.side.addWidget(self.snap_check)
        self.visible_check = QCheckBox('Показать направляющие')
        self.visible_check.setChecked(True)
        self.visible_check.toggled.connect(self.guides_visible)
        self.side.addWidget(self.visible_check)
        main = self.side
        detail = Foldout('Дополнительно')
        main.addWidget(detail)
        self.side = detail.content
        self.extensions_check = QCheckBox('Продлить линии перспективы')
        self.extensions_check.toggled.connect(self.extensions)
        self.side.addWidget(self.extensions_check)
        self.slider('Скорость мыши', 'mouse_gain', 20, 250, 100, 100, '×')
        main.addStretch()

    def build_sheets_page(self):
        self.inspector_page('Лист', 'Свойства листа')
        actions = QHBoxLayout()
        actions.addWidget(button('+ Лист', self.new_paper))
        self.tracing_button = button('+ Калька', lambda: self.board.add_tracing(), 'Положить кальку над выбранным листом · T')
        actions.addWidget(self.tracing_button)
        self.side.addLayout(actions)
        self.object_list = QListWidget()
        self.object_list.setObjectName('sheets')
        self.object_list.setIconSize(QSize(60, 44))
        self.object_list.setSpacing(4)
        self.object_list.setMinimumHeight(84)
        self.object_list.setMaximumHeight(220)
        self.object_list.setHorizontalScrollBarPolicy(Qt.ScrollBarPolicy.ScrollBarAlwaysOff)
        self.object_list.setFocusPolicy(Qt.FocusPolicy.NoFocus)
        self.object_list.currentRowChanged.connect(self.choose_object)
        self.side.addWidget(self.object_list)
        self.object_list.hide()
        self.side.addWidget(label('Листы и папки — во вкладках над холстом', 'muted'))
        self.side.addWidget(label('Бумага выбранного листа', 'muted'))
        self.paper_combo = QComboBox()
        for key, (title, color, _) in PAPER_STYLES.items():
            swatch = QPixmap(18, 18)
            swatch.fill(QColor(color))
            self.paper_combo.addItem(QIcon(swatch), title, key)
        self.paper_combo.setToolTip('Бумага меняется без изменения штрихов. Ctrl+Z — отмена.')
        self.paper_combo.currentIndexChanged.connect(self.change_paper_style)
        self.side.addWidget(self.paper_combo)
        self.paper_alpha_label = label('Прозрачность бумаги · 0%', 'muted')
        self.side.addWidget(self.paper_alpha_label)
        self.paper_alpha = QSlider(Qt.Orientation.Horizontal)
        self.paper_alpha.setRange(0, 100)
        self.paper_alpha.setFocusPolicy(Qt.FocusPolicy.NoFocus)
        self.paper_alpha.valueChanged.connect(self.paper_transparency)
        self.side.addWidget(self.paper_alpha)
        self.ink_alpha_label = label('Видимость рисунка · 100%', 'muted')
        self.side.addWidget(self.ink_alpha_label)
        self.ink_alpha = QSlider(Qt.Orientation.Horizontal)
        self.ink_alpha.setRange(0, 100)
        self.ink_alpha.setValue(100)
        self.ink_alpha.setFocusPolicy(Qt.FocusPolicy.NoFocus)
        self.ink_alpha.valueChanged.connect(self.ink_visibility)
        self.side.addWidget(self.ink_alpha)
        from .guide_panel import GuidePanel
        guide_fold = Foldout('Слои направляющих · Alt')
        self.guide_panel = GuidePanel(self)
        guide_fold.content.addWidget(self.guide_panel)
        self.side.addWidget(guide_fold)
        guide_fold.toggle.setChecked(True)
        main = self.side
        self.sheet_detail = Foldout('Свойства и порядок')
        main.addWidget(self.sheet_detail)
        self.side = self.sheet_detail.content
        self.object_name = QLineEdit()
        self.object_name.setPlaceholderText('Название листа / референса')
        self.object_name.editingFinished.connect(self.rename_object)
        self.side.addWidget(self.object_name)
        transforms = QHBoxLayout()
        self.angle = QSpinBox()
        self.angle.setRange(-180, 180)
        self.angle.setSuffix('°')
        self.angle.setPrefix('↻ ')
        self.angle.setToolTip('Поворот выбранного листа')
        self.angle.valueChanged.connect(lambda value: self.transform_object('angle', value))
        self.scale = QSpinBox()
        self.scale.setRange(8, 800)
        self.scale.setSuffix('%')
        self.scale.setToolTip('Масштаб выбранного листа')
        self.scale.valueChanged.connect(lambda value: self.transform_object('scale', value/100))
        transforms.addWidget(self.angle)
        transforms.addWidget(self.scale)
        self.side.addLayout(transforms)
        actions = QHBoxLayout()
        actions.addWidget(button('Наверх', self.raise_object))
        actions.addWidget(button('Удалить', lambda: self.board.delete_selected(), 'Удалить объект · Delete · отмена Ctrl+Z'))
        self.side.addLayout(actions)
        self.lock_check = QCheckBox('Закрепить объект')
        self.lock_check.toggled.connect(lambda value: self.transform_object('locked', value))
        self.side.addWidget(self.lock_check)
        self.clear_button = button('Очистить рисунок', self.clear_current_paper, 'Удалить штрихи выбранного листа · Alt — только выбранный слой направляющих · Ctrl+Shift+Delete · Ctrl+Z — отмена')
        main.insertWidget(2, self.clear_button)
        main.addStretch()
